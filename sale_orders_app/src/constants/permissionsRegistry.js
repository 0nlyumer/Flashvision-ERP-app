// anywhere in the ERP, its entries MUST be added here in the same change —
// exactly like its database tables — so User Control stays aligned.
//
// Screen ids intentionally match the app's own tab/view ids where they exist
// (Layout sub-nav and module tab filters check hasPermission(module, screenId)
// with those same ids). Action ids are stable; never rename a shipped id.
